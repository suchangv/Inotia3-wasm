#!/bin/sh
# Regenerate src/gl4es_protos.h from gl4es' own GLES1 header.
#
# The prototypes are lifted mechanically rather than written by hand: a wrong
# parameter type in this header is not a compile error at the boundary, it is a
# silently mis-called function. Run this after changing gl4es' revision.
set -e
cd "$(dirname "$0")/.."
SRC=${1:-vendor/gl4es/include/GLES/gl.h}
[ -f "$SRC" ] || { echo "no header at $SRC -- run tools/build_gl4es.sh first"; exit 1; }
python3 - "$SRC" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
typedefs = [m.group(0).strip() for m in re.finditer(r'typedef\s+[^;]+?GL\w+\s*;', src)
            if 'GL_API' not in m.group(0) and 'GL_APIENTRY' not in m.group(0)]
decls = []
for line in src.splitlines():
    m = re.match(r'GL_API\s+(.+?)\s+GL_APIENTRY\s+(gl\w+)\s*\((.*)\)\s*;', line.strip())
    if m:
        decls.append((m.group(2), m.group(1).strip(), m.group(3).strip()))
out = ["/*", " * gl4es_protos.h -- GENERATED from gl4es' include/GLES/gl.h; do not edit.",
       " *", " * Generated by tools/gen_gl4es_protos.sh.", " *", " * GL4ES(name, return-type, (parameter-list))", " */",
       "#ifndef GL4ES_PROTOS_H", "#define GL4ES_PROTOS_H", "",
       "typedef signed char        khronos_int8_t;", "typedef unsigned char      khronos_uint8_t;",
       "typedef signed int         khronos_int32_t;", "typedef signed long int    khronos_intptr_t;",
       "typedef signed long int    khronos_ssize_t;", "typedef float              khronos_float_t;", ""]
out += typedefs + [""]
out += ["GL4ES(%s, %s, (%s))" % d for d in decls]
out += ["", "#endif /* GL4ES_PROTOS_H */"]
open('src/gl4es_protos.h','w').write("\n".join(out) + "\n")
print("wrote src/gl4es_protos.h: %d typedefs, %d prototypes" % (len(typedefs), len(decls)))
PY
